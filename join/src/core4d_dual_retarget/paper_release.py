"""Freeze a self-contained, checksumed Join paper result bundle."""

from __future__ import annotations

import hashlib
import importlib.metadata
import json
import platform
import shutil
import subprocess
from pathlib import Path


def _git_output(repo_root: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", *args],
        cwd=repo_root,
        check=False,
        capture_output=True,
        text=True,
    )
    return result.stdout.strip() if result.returncode == 0 else "UNAVAILABLE"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def freeze_join_paper_release(
    repo_root: Path,
    paper_root: Path,
    output_root: Path,
) -> None:
    """Copy evaluated artifacts and provenance, refusing any overwrite."""
    if output_root.exists():
        raise FileExistsError(f"Refusing to overwrite frozen release: {output_root}")
    output_root.mkdir(parents=True)
    for source_name, destination_name in (
        ("ablation_018", "ablation"),
        ("final_six", "final_six"),
        ("summary", "tables"),
        ("figures", "figures"),
    ):
        source = paper_root / source_name
        if not source.exists():
            raise FileNotFoundError(source)
        shutil.copytree(source, output_root / destination_name)

    config_root = output_root / "config"
    config_root.mkdir()
    for path in sorted(paper_root.glob("ablation_018/J*/config.json")):
        shutil.copy2(path, config_root / f"{path.parent.name}.json")
    for path in sorted(paper_root.glob("final_six/*/config.json")):
        shutil.copy2(path, config_root / f"final_{path.parent.name}.json")

    packages = {}
    for package in (
        "numpy",
        "scipy",
        "trimesh",
        "torch",
        "pytorch-kinematics",
        "mujoco",
        "matplotlib",
        "imageio",
    ):
        try:
            packages[package] = importlib.metadata.version(package)
        except importlib.metadata.PackageNotFoundError:
            packages[package] = "not-installed"
    version = {
        "git_commit": _git_output(repo_root, "rev-parse", "HEAD"),
        "git_branch": _git_output(repo_root, "branch", "--show-current"),
        "git_status": _git_output(repo_root, "status", "--short"),
        "python": platform.python_version(),
        "platform": platform.platform(),
        "packages": packages,
    }
    (output_root / "code_version.txt").write_text(
        json.dumps(version, indent=2) + "\n", encoding="utf-8"
    )

    reproduction_source = repo_root / "scripts" / "run_join_paper_experiments.sh"
    shutil.copy2(reproduction_source, output_root / "run_join_paper_experiments.sh")
    reproduction = """# Join paper release reproduction

This release was generated by the controlled, non-destructive paper pipeline.

## Full regeneration

From the repository root:

```bash
PAPER_ROOT=outputs/paper_eval_join_repro \
  bash scripts/run_join_paper_experiments.sh
```

The script refuses to overwrite an existing paper root. J0--J4 use the same
independent-IK initialization and identical smoothing. Frozen v41 six-sequence
artifacts are copied and evaluated, never modified.

## Metric contract

- fps: 15
- robot contact hysteresis: enter 0.04 m, exit 0.055 m
- contact geometry: official rubber-hand samples for every method
- smoothing: sigma 1, arm sigma 0.35, root sigma 0, sole lift enabled
- derivative metrics: finite differences multiplied by fps**order
- six-sequence aggregate: mean/std over six sequence averages

## Scope limitation

All trajectories are kinematic references. Free-base PD does not stably track
them; this bundle makes no dynamic execution or sim-to-real claim.
"""
    (output_root / "reproduction.md").write_text(reproduction, encoding="utf-8")

    checksums = {}
    for path in sorted(output_root.rglob("*")):
        if path.is_file() and path.name != "checksums_sha256.json":
            checksums[str(path.relative_to(output_root))] = _sha256(path)
    (output_root / "checksums_sha256.json").write_text(
        json.dumps(checksums, indent=2) + "\n", encoding="utf-8"
    )
